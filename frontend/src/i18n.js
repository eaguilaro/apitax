const storedLanguage = localStorage.getItem('apitax-language')
const locale = ref(storedLanguage === 'en' ? 'en' : 'es')

watch(locale, (value) => {
  localStorage.setItem('apitax-language', value)
  document.documentElement.lang = value
  Quasar.lang.set(value === 'es' ? spanishQuasar : englishQuasar)
}, { immediate: true })

function t(key, params = {}) {
  let value = translations[locale.value][key] || translations.es[key] || key
  for (const [name, replacement] of Object.entries(params)) {
    value = value.replaceAll(`{${name}}`, String(replacement))
  }
  return value
}

function setLanguage(language) {
  locale.value = language === 'en' ? 'en' : 'es'
}

export function useI18n() {
  return { locale, setLanguage, t }
}
